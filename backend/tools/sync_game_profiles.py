#!/usr/bin/env python3
"""Generate browser JSON and C++ constexpr bindings from canonical profile.

Use --check in parity/CI; no ROM or fixture input is needed. Native cores embed
exact canonical JSON for inspection and use generated typed values for logic.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))
from core.profile_schema import validate_contract

SOURCE = ROOT / 'backend/data/profiles/unbound-2.1.1.1.json'


def camel(parts):
    return ''.join(word.title() for part in parts for word in part.split('_'))


def generate_header(profile, serialized):
    lines = ['// Generated by backend/tools/sync_game_profiles.py. Do not hand edit.',
             '#pragma once', '#include <array>', '#include <cstddef>', '#include <cstdint>',
             '#include <cstring>', '#include <string>', 'namespace puse::core::profile {']
    def visit(value, parts):
        name = 'k' + camel(parts)
        if isinstance(value, dict):
            for key, child in value.items(): visit(child, parts + [key])
        elif isinstance(value, bool): lines.append(f'inline constexpr bool {name} = {str(value).lower()};')
        elif isinstance(value, int): lines.append(f'inline constexpr uint32_t {name} = {value}U;')
        elif isinstance(value, str): lines.append(f'inline constexpr const char* {name} = {json.dumps(value)};')
        elif isinstance(value, list) and all(isinstance(x, int) for x in value):
            lines.append(f'inline constexpr std::array<uint32_t, {len(value)}> {name} = {{{", ".join(str(x)+"U" for x in value)}}};')
    visit(profile, [])
    regions = profile['storage']['pc']['regions']
    lines.append('struct Region { uint32_t id, start, end; };')
    lines.append(f'inline constexpr std::array<Region, {len(regions)}> kPcRegions = {{{{')
    lines += [f'    {{{sid}U, {start}U, {end}U}},' for sid,start,end in regions]
    lines.append('}};')
    lines += ['struct GameProfile { const char* id; const char* serialized; };',
              'inline constexpr const char kSerialized[] = R"PUSEPROFILE(' + serialized + ')PUSEPROFILE";',
              'inline constexpr GameProfile kBuiltin{kId, kSerialized};',
              'inline const GameProfile* FindProfile(const std::string& id) { return id == kId ? &kBuiltin : nullptr; }',
              'inline size_t ChecksumLength(uint16_t id) {']
    for sid,length in profile['container']['checksum']['lengths'].items():
        lines.append(f'    if (id == {sid}) return {length};')
    lines += ['    return kContainerChecksumDefaultLength;', '}',
              'inline bool Opaque(uint16_t id) { for (auto value : kContainerChecksumOpaqueIds) if (id == value) return true; return false; }',
              'inline std::string CatalogAsset(const char* filename) {']
    for entry in profile['catalogs'].values():
        file = entry['file']
        lines.append(f'    if (std::strcmp(filename, "{file}") == 0) return "data/{file}";')
    lines += ['    return {};', '}',
              'struct NativeIdentity { std::string profile_id; uint32_t native_id; };',
              'inline NativeIdentity Identity(uint32_t id) { return {kId, id}; }',
              'enum class RecordState { Empty, Known, Unknown };',
              'inline RecordState InspectPcRecord(const uint8_t* raw, size_t size, bool known_species) {',
              '    if (size != kCodecsPcRecordSize) return RecordState::Unknown;',
              '    const auto off = kCodecsPcFieldsSpecies;',
              '    const auto id = uint16_t(raw[off]) | (uint16_t(raw[off+1]) << 8);',
              '    return id == 0 ? RecordState::Empty : known_species ? RecordState::Known : RecordState::Unknown;',
              '}', '} // namespace puse::core::profile', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    serialized = SOURCE.read_text()
    profile = validate_contract(json.loads(serialized))
    assert profile['schema_version'] == 1
    assert re.fullmatch(r'[a-z0-9.-]+', profile['id'])
    pc = profile['storage']['pc']
    assert sum(end-start for _,start,end in pc['regions']) == pc['box_count']*pc['slots_per_box']*pc['record_size']
    for entry in profile['catalogs'].values():
        assert (ROOT/'backend/data'/entry['file']).is_file(), entry
    outputs = {ROOT/'frontend/src/core/gameProfile.json':serialized}
    header = generate_header(profile, serialized)
    for port in ['switch-homebrew','3ds-homebrew']:
        outputs[ROOT/port/'include/puse/core/GameProfile.hpp'] = header
        if args.check:
            outputs[ROOT/port/'romfs/data/profiles'/SOURCE.name] = serialized
    for path, content in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text() != content: raise SystemExit(f'Stale profile binding: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True); path.write_text(content)
    print('Game profile bindings are current.' if args.check else 'Generated game profile bindings.')


if __name__ == '__main__': main()
