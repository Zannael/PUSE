#!/usr/bin/env python3
"""Generate runtime pocket maps and fallback sets from extracted ROM records.

Run the item extractor first, this tool with --write, then both ROMFS data sync
scripts. --check verifies all consumers without changing files.
"""
import argparse
import json
from pathlib import Path
import re

from extract_unbound_item_table import runtime_pocket_map

ROOT = Path(__file__).resolve().parents[2]
MAP = ROOT / 'backend/data/item_pocket_map.json'
TABLE = ROOT / 'backend/data/item_table_from_rom.json'


def generated_files(table):
    payload = runtime_pocket_map(table['items'])
    encoded = json.dumps(payload, indent=2) + '\n'
    encoded = re.sub(r'"ids": \[([^\]]*)\]',
                     lambda m: '"ids": [' + ', '.join(re.findall(r'\d+', m[1])) + ']', encoded)
    files = {MAP: encoded, ROOT / 'frontend/src/core/itemPocketMap.json': encoded}
    ids = {key: value['ids'] for key, value in payload['pockets'].items() if 'ids' in value}
    comment = 'Generated by backend/tools/sync_item_pocket_data.py; do not edit.'

    path = ROOT / 'backend/modules/bag.py'
    source = path.read_text()
    lines = ['def _fallback_pocket_sets():', f'    # {comment}']
    for key in ('ball', 'berry', 'tm', 'hm', 'key'):
        lines.append(f'    {key} = {{{", ".join(map(str, ids[key]))}}}')
    lines += ['    return ball, berry, tm, hm, (tm | hm), key', '', '']
    start = source.index('def _fallback_pocket_sets():')
    end = source.index('def _set_from_json_list', start)
    files[path] = source[:start] + '\n'.join(lines) + '\n' + source[end:]

    path = ROOT / 'frontend/src/core/bag.js'
    source = path.read_text()
    start = source.index('const FALLBACK_BALL_IDS =')
    end = source.index('if (BALL_ITEM_IDS.size', start)
    if source[:start].endswith(f'// {comment}\n'):
        start -= len(f'// {comment}\n')
    lines = [f'// {comment}']
    for key in ('ball', 'berry', 'tm', 'hm', 'key'):
        lines.append(f'const FALLBACK_{key.upper()}_IDS = [{", ".join(map(str, ids[key]))}];')
    files[path] = source[:start] + '\n'.join(lines) + '\n\n' + source[end:]

    for port in ('switch-homebrew', '3ds-homebrew'):
        path = ROOT / port / 'source/core/Bag.cpp'
        source = path.read_text()
        start = source.index('void LoadFallbackPocketSets() {')
        end = source.index('std::vector<int> ParseIntArray', start)
        lines = ['void LoadFallbackPocketSets() {', f'    // {comment}']
        for key in ('ball', 'berry', 'tm', 'hm', 'key'):
            lines.append(f'    g_{key}_ids = {{{", ".join(map(str, ids[key]))}}};')
        lines += ['    g_tmhm_ids = g_tm_ids;', '    for (auto id : g_hm_ids) { g_tmhm_ids.insert(id); }', '}', '', '']
        files[path] = source[:start] + '\n'.join(lines) + '\n' + source[end:]
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--write', action='store_true')
    mode.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = generated_files(json.loads(TABLE.read_text()))
    if args.check:
        for port in ('switch-homebrew', '3ds-homebrew'):
            files[ROOT / port / 'romfs/data/item_pocket_map.json'] = files[MAP]
            files[ROOT / port / 'romfs/data/item_table_from_rom.json'] = TABLE.read_text()
    stale = []
    for path, expected in files.items():
        if args.write:
            path.write_text(expected)
        elif path.read_text() != expected:
            stale.append(str(path.relative_to(ROOT)))
    if stale:
        raise SystemExit('Stale generated pocket data: ' + ', '.join(stale))
    print('Generated pocket maps and fallback sets are current.' if args.check else
          'Generated pocket maps and fallback sets. Run both ROMFS data sync scripts.')


if __name__ == '__main__':
    main()
