#!/usr/bin/env python3
"""Deterministic mirrors of graphics descriptors and a small C++ trust registry."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def sync():
    source = ROOT / 'backend/data/graphics'
    target = ROOT / 'frontend/src/data/graphics'
    target.mkdir(parents=True, exist_ok=True)
    for name in ('roms.json', 'fallbacks.json'):
        if (source / name).exists():
            (target / name).write_bytes((source / name).read_bytes())
    data = json.loads((source / 'roms.json').read_text())
    fallbacks = json.loads((source / 'fallbacks.json').read_text())
    lines = [f'{profile}\t{kind}\t{native_id}\t{filename}' for profile, kinds in sorted(fallbacks.items())
             for kind, rows in sorted(kinds.items()) for native_id, filename in sorted(rows.items(), key=lambda kv: int(kv[0]))]
    (source / 'fallbacks.tsv').write_text('\n'.join(lines) + '\n')
    header = ('// Generated by backend/tools/sync_graphics_data.py.\n#pragma once\n#include <string>\n'
              'namespace puse::core::graphics {\ninline bool Trusted(const std::string& profile, const std::string& hash) {\n')
    header += 'return ' + ' ||\n'.join(f'(profile == "{r["profile_id"]}" && hash == "{r["sha256"]}")' for r in data['roms']) + ';\n}\n}\n'
    for port in ('switch-homebrew', '3ds-homebrew'):
        (ROOT / port / 'include/puse/core/GraphicsRegistry.hpp').write_text(header)
        (ROOT / port / 'include/puse/core/GraphicsPack.hpp').write_bytes((ROOT / 'shared/graphics/GraphicsPack.hpp').read_bytes())


if __name__ == '__main__':
    sync()
