import assert from 'node:assert/strict';
import fs from 'node:fs';
import { loadPcContext, insertPcMon, releasePcMon, applyPcContextToSave } from '../src/core/pc.js';
import { PROFILE, getProfile, nativeIdentity, inspectPcRecord, catalogFile } from '../src/core/profile.js';
import { loadFile, getSessionProfile, getBuffer, updateBuffer, setBuffer } from '../src/core/saveSession.js';

assert.throws(() => getProfile('unknown'), /Unsupported game profile/);
assert.throws(() => { PROFILE.rules.shiny_threshold = 8; }, TypeError);
assert.deepEqual(nativeIdentity(65535), ['unbound-2.1.1.1', 65535]);
assert.equal(catalogFile('species'), 'pokemon.txt');
assert.throws(() => catalogFile('unknown'), /Unknown profile catalog/);
assert.throws(() => getSessionProfile(), /No save loaded/);
const source = new Uint8Array(fs.readFileSync(process.argv[2]));
await loadFile({ name: 'synthetic.sav', arrayBuffer: async () => source.buffer });
assert.equal(getSessionProfile(), PROFILE);
updateBuffer((bytes) => { bytes[0] ^= 1; });
assert.equal(getSessionProfile(), PROFILE);
setBuffer(source);
assert.equal(getSessionProfile(), PROFILE);
assert.deepEqual(getBuffer(), source);
const unknown = new Uint8Array(58);
assert.equal(inspectPcRecord(unknown).state, 'empty');
unknown[28] = 255; unknown[29] = 255;
const inspected = inspectPcRecord(unknown);
assert.equal(inspected.state, 'unknown');
assert.deepEqual(inspected.identity, nativeIdentity(65535));
assert.deepEqual(inspected.raw, unknown);
assert.equal(inspectPcRecord(unknown, new Set([65535])).state, 'known');
assert.throws(() => inspectPcRecord(new Uint8Array(57)), /Invalid compact record width/);
const context = loadPcContext(source);
const before = new Uint8Array(context.pcBuffer);
context.presetBuffer[0xB0+28] = 255;
context.presetBuffer[0xB0+29] = 255;
const presetBefore = new Uint8Array(context.presetBuffer);
assert.throws(() => insertPcMon(context, {box: 26, slot: 1, species_id: 1, level: 5}), /occupied/);
assert.deepEqual(context.presetBuffer, presetBefore);
assert.throws(() => insertPcMon(context, {box: 1, slot: 2, species_id: 1, level: 5}), /occupied/);
assert.deepEqual(context.pcBuffer, before, 'unknown insertion changed storage');
releasePcMon(context, {box: 1, slot: 3});
assert.deepEqual(context.pcBuffer.slice(58,116), before.slice(58,116));
applyPcContextToSave(source, context);
assert.deepEqual(loadPcContext(source).pcBuffer.slice(58,116), before.slice(58,116));
process.stdout.write(JSON.stringify(PROFILE));
