import fs from 'node:fs';
import assert from 'node:assert/strict';
import { chooseProfile, activateProfile, requireCapability, PROFILE } from '../src/core/profile.js';
import { loadPcContext, applyPcContextToSave, editPcMonFull, insertPcMon } from '../src/core/pc.js';
import { updatePartyHappiness, updatePartyItem, updatePartyNature, updatePartyMoves, updatePartyIdentity, updatePartyNickname, updatePartyOtName } from '../src/core/party.js';
import { updateMoney, updateBp } from '../src/core/money.js';
import { radicalBagOffsets, radicalBagWrite } from '../src/core/radicalBag.js';
import { loadCatalog } from '../src/core/catalog.js';
import { activeUnboundSlot } from '../src/core/sections.js';
import { ru16 } from '../src/core/binary.js';
const save=new Uint8Array(fs.readFileSync(process.argv[2]));
assert.throws(()=>chooseProfile(save), /Explicit/);
await activateProfile(chooseProfile(save,'radical-red-4.1'));
await loadCatalog();
assert.equal(PROFILE.rules.shiny_threshold,8);
const context=loadPcContext(save);assert.equal(context.pcBuffer.length,43500);
const before=save.slice();applyPcContextToSave(save,context);assert.deepEqual(save,before);
assert.throws(()=>insertPcMon(context,{}), /Unsupported/);
assert.throws(()=>updateBp(save,5), /Unsupported/);assert.deepEqual(save,before);
assert.throws(()=>requireCapability('pokedex'), /Unsupported/);
const selected=activeUnboundSlot(save);const damaged=save.slice();damaged[selected.get(4).offset+4]^=1;
assert.notEqual(activeUnboundSlot(damaged).get(0).idx,selected.get(0).idx);
const pockets=radicalBagOffsets(save);
for(const key of ['key','tm','ball']) assert.throws(()=>radicalBagWrite(save,pockets[key][0],13,key==='ball'?1:0), /different bag pocket/);
const firstEmpty=pockets.key.findIndex((off)=>ru16(save,off)===0);
assert.throws(()=>radicalBagWrite(save,pockets.key[firstEmpty+1],ru16(save,pockets.key[0]),1), /first empty/);
assert.deepEqual(save,before);
if(process.argv[4]==='edit') {
 updatePartyHappiness(save,0,{happiness:123});
 updatePartyItem(save,0,{item_id:616});
 updatePartyNature(save,0,{nature_id:3});
 updatePartyMoves(save,0,{moves:[1003,999,0,33],move_pp:[99,99,0,99],move_pp_ups:[3,2,0,1]});
 updatePartyIdentity(save,0,{shiny:true});updatePartyNickname(save,0,{nickname:"RR TEST"});updatePartyOtName(save,0,{ot_name:"PUSE"});
 editPcMonFull(context,{box:25,slot:1,happiness:91});applyPcContextToSave(save,context);
 updateMoney(save,123456789);
 const layout=radicalBagOffsets(save);
 for(const positions of Object.values(layout)) radicalBagWrite(save,positions[0],ru16(save,positions[0]),17);
 radicalBagWrite(save,layout.main[0],0,0);
}
fs.writeFileSync(process.argv[3],save);
